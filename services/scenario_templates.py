def get_template_info(template_id: str) -> Optional[Dict]:
    """
    Получить информацию о шаблоне по ID
    
    Args:
        template_id: ID шаблона
        
    Returns:
        Dict с информацией о шаблоне или None
    """
    return SCENARIO_TEMPLATES.get(template_id)


def get_template_prompt_modifier(template_id: str) -> str:
    """
    Получить модификатор промпта для шаблона
    
    Args:
        template_id: ID шаблона
        
    Returns:
        str: Модификатор промпта или пустая строка
    """
    template = SCENARIO_TEMPLATES.get(template_id)
    if template:
        return template.get("prompt_modifier", "")
    return ""


def get_all_templates() -> Dict[str, Dict]:
    """
    Получить все доступные шаблоны
    
    Returns:
        Dict со всеми шаблонами
    """
    return SCENARIO_TEMPLATES

